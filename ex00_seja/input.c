int	ft_parse_input(char *str, int *clues)
{
	int	i;

	i = 0;
	while (i < 16)
	{
		if (str[i * 2] < '1' || str[i * 2] > '4')
			return (0);
		clues[i] = str[i * 2] - '0';
		if (i < 15 && str[i * 2 + 1] != ' ')
			return (0);
		i++;
	}
	return (str[31] == '\0');
}
